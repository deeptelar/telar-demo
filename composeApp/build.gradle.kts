/**
 * Writes the text of source files into a Kotlin file. The game shows the code of a node when its
 * tile is pressed, and reads it from there, so what it shows is always the code that runs.
 */
abstract class EmbedSources : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val sources: ConfigurableFileCollection

    /** The package of the file that is written, and the name of the value in it. */
    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val valueName: Property<String>

    /** What the value is, for its comment. */
    @get:Input
    abstract val what: Property<String>

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun write() {
        val entries = sources.files.sortedBy { it.name }.joinToString("\n") { file ->
            val text = file.readText().replace("\r", "")
            val literal = text.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$").replace("\n", "\\n")
            "    \"${file.name}\" to \"$literal\","
        }
        val name = valueName.get()
        val file = output.get().asFile.resolve("${packageName.get().replace('.', '/')}/${name.replaceFirstChar { it.uppercase() }}.kt")
        file.parentFile.mkdirs()
        file.writeText(
            "package ${packageName.get()}\n\n" +
                "/** ${what.get()}, by file name. Generated by the build; do not edit. */\n" +
                "internal val $name: Map<String, String> = mapOf(\n$entries\n)\n",
        )
    }
}

val embedStageSources by tasks.registering(EmbedSources::class) {
    sources.from(
        "src/commonMain/kotlin/dev/deeptelar/telar/demo/game/HelpDesks.kt",
        "src/commonMain/kotlin/dev/deeptelar/telar/demo/game/Agent.kt",
    )
    packageName.set("dev.deeptelar.telar.demo.game")
    valueName.set("stageSources")
    what.set("The source files of the stage graphs")
    output.set(layout.buildDirectory.dir("generated/stageSources"))
}

